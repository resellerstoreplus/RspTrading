/* =====================================================
   LANGUAGE SYSTEM
===================================================== */

function setLanguage(language) {

    const elements =
        document.querySelectorAll("[data-i18n]");


    elements.forEach(element => {

        const key =
            element.getAttribute("data-i18n");


        if (
            translations[language] &&
            translations[language][key]
        ) {

            element.innerHTML =
                translations[language][key];

        }

    });


    document.documentElement.lang =
        language;


    localStorage.setItem(
        "rspTradingLanguage",
        language
    );


    document.getElementById(
        "languageSelect"
    ).value = language;


    document.getElementById(
        "mobileLanguage"
    ).value = language;
}



/* LANGUAGE SELECT */

const languageSelect =
    document.getElementById(
        "languageSelect"
    );


const mobileLanguage =
    document.getElementById(
        "mobileLanguage"
    );


languageSelect.addEventListener(
    "change",
    function() {

        setLanguage(
            this.value
        );

    }
);


mobileLanguage.addEventListener(
    "change",
    function() {

        setLanguage(
            this.value
        );


        document
            .getElementById("navLinks")
            .classList.remove("open");


        document
            .getElementById("menuToggle")
            .textContent = "☰";

    }
);



/* LOAD SAVED LANGUAGE */

const savedLanguage =
    localStorage.getItem(
        "rspTradingLanguage"
    ) || "en";


setLanguage(savedLanguage);



/* =====================================================
   MOBILE MENU
===================================================== */

const menuToggle =
    document.getElementById(
        "menuToggle"
    );


const navLinks =
    document.getElementById(
        "navLinks"
    );


menuToggle.addEventListener(
    "click",
    function() {

        navLinks.classList.toggle(
            "open"
        );


        if (
            navLinks.classList.contains(
                "open"
            )
        ) {

            menuToggle.textContent = "×";

        } else {

            menuToggle.textContent = "☰";

        }

    }
);



/* CLOSE MOBILE MENU */

document
    .querySelectorAll(".nav-links a")
    .forEach(link => {

        link.addEventListener(
            "click",
            function() {

                navLinks
                    .classList
                    .remove("open");

                menuToggle.textContent =
                    "☰";

            }
        );

    });



/* =====================================================
   COUNTER
===================================================== */

const counter =
    document.getElementById(
        "counter"
    );


let current = 1240;

const target = 1284;


const counterTimer =
    setInterval(
        function() {

            current++;

            counter.textContent =
                current.toLocaleString();

            if (current >= target) {

                clearInterval(
                    counterTimer
                );

            }

        },
        35
    );



